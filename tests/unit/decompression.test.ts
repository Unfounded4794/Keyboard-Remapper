import { createRequire } from "node:module";
import { it, expect } from "vitest";
const require = createRequire(import.meta.url);
const { decompressDefinition } = require("../../electron/definitions.cjs");
// Small XZ fixture from xz-decompress's upstream test suite (MIT).
const xz =
  "/Td6WFoAAATm1rRGAgAhARYAAAB0L+WjAQALaGVsbG8gd29ybGQKAKHy/8Rqf7/PAAEkDKYY2NgftvN9AQAAAAAEWVo=";
it("decompresses the XZ container generated by Vial’s Python lzma compressor", async () => {
  expect(await decompressDefinition([...Buffer.from(xz, "base64")])).toBe(
    "hello world\n",
  );
});
it("retains support for LZMA-alone definitions", async () => {
  const text = '{"name":"Example","matrix":{"rows":1,"cols":1}}';
  const bytes = require("lzma")
    .compress(text, 1)
    .map((b: number) => b & 255);
  expect(await decompressDefinition(bytes)).toBe(text);
});
it("rejects invalid bytes and excessive declared decompressed sizes", async () => {
  await expect(
    decompressDefinition([256, ...Array(20).fill(0)]),
  ).rejects.toThrow(/Invalid/);
  await expect(
    decompressDefinition([93, 0, 0, 1, 0, ...Array(8).fill(255)]),
  ).rejects.toThrow(/2 MiB/);
});
